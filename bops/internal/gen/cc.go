package gen

import (
	"bytes"
	_ "embed"
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/extremenelson/beads-ops/bops/internal/manifest"
)

// ccPreamble is the hand-written part of the Claude Code skill: frontmatter
// and the loop prose. The command reference after it is generated.
//
//go:embed templates/cc-preamble.md
var ccPreamble []byte

// ccBopsNext is the /bops-next slash command, emitted when the manifest
// offers next to the skill.
//
//go:embed templates/cc-bops-next.md
var ccBopsNext []byte

// CC renders the Claude Code binding (SPEC.md §8): skills/bops/SKILL.md (the
// preamble plus a reference of every command whose surfaces.cc lists
// "skill"), hooks.json (one SessionStart hook per command listing
// "hook:SessionStart") and commands/bops-next.md.
func CC(m *manifest.Manifest) ([]File, error) {
	var skill []manifest.Command
	hooks := map[string][]ccHookGroup{}
	for _, c := range m.Commands {
		for _, s := range ccSurfaces(c) {
			switch {
			case s == "skill":
				skill = append(skill, c)
			case strings.HasPrefix(s, "hook:"):
				h, err := ccHook(c, strings.TrimPrefix(s, "hook:"))
				if err != nil {
					return nil, err
				}
				ev := strings.TrimPrefix(s, "hook:")
				hooks[ev] = append(hooks[ev], h)
			default:
				return nil, fmt.Errorf("gen cc: %s: unknown cc surface %q", c.Name, s)
			}
		}
	}
	if len(skill) == 0 {
		return nil, fmt.Errorf("gen cc: no command has a cc skill surface")
	}

	var b bytes.Buffer
	b.Write(ccPreamble)
	if !bytes.HasSuffix(ccPreamble, []byte("\n")) {
		b.WriteString("\n")
	}
	fmt.Fprintf(&b, "\n## Command reference (contract %d)\n\n", m.Contract)
	fmt.Fprintf(&b, "Generated by `bops gen cc`. If `bops version` reports a contract other than %d, stop and tell the person: this skill does not match the binary.\n\n", m.Contract)
	b.WriteString("Exit codes: ")
	codes := make([]string, 0, len(m.Common.Exit))
	for k := range m.Common.Exit {
		codes = append(codes, k)
	}
	sort.Strings(codes)
	for i, k := range codes {
		if i > 0 {
			b.WriteString("; ")
		}
		fmt.Fprintf(&b, "**%s** %s", k, m.Common.Exit[k])
	}
	b.WriteString(".\n\n| Command | Kind | Intent |\n|---|---|---|\n")
	for _, c := range skill {
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", ccSignature(c), c.Kind, c.Intent)
	}
	files := []File{{Path: "skills/bops/SKILL.md", Data: b.Bytes()}}

	hj, err := json.MarshalIndent(struct {
		Comment string                   `json:"_comment"`
		Hooks   map[string][]ccHookGroup `json:"hooks"`
	}{
		Comment: fmt.Sprintf("Generated by `bops gen cc` from bops/commands.json (contract %d). Merge into .claude/settings.json; bindings/claude-code/README.md says why there is no Stop or PreCompact hook.", m.Contract),
		Hooks:   hooks,
	}, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("gen cc: hooks.json: %w", err)
	}
	files = append(files, File{Path: "hooks.json", Data: append(hj, '\n')})

	for _, c := range skill {
		if c.Name == "next" {
			files = append(files, File{Path: "commands/bops-next.md", Data: ccBopsNext})
		}
	}
	return files, nil
}

type ccHookGroup struct {
	Matcher string      `json:"matcher"`
	Hooks   []ccHookCmd `json:"hooks"`
}

type ccHookCmd struct {
	Type    string `json:"type"`
	Command string `json:"command"`
}

// ccHook builds the hook entry for a command. Only SessionStart is generated:
// Stop fires after every reply, too often for a pushing sync, and a PreCompact
// hook's output never reaches the model (SPEC.md §8). The command must take
// --hook-json, since Claude Code parses bare JSON on stdout as hook control
// and injects nothing.
func ccHook(c manifest.Command, event string) (ccHookGroup, error) {
	if event != "SessionStart" {
		return ccHookGroup{}, fmt.Errorf("gen cc: %s: hook:%s: only SessionStart hooks are generated (SPEC.md §8)", c.Name, event)
	}
	if _, ok := c.Args["hook-json"]; !ok {
		return ccHookGroup{}, fmt.Errorf("gen cc: %s: hook:%s needs a hook-json arg to wrap its output for Claude Code", c.Name, event)
	}
	return ccHookGroup{Matcher: "", Hooks: []ccHookCmd{{Type: "command", Command: "bops " + c.Name + " --hook-json || true"}}}, nil
}

// ccSurfaces reads surfaces.cc, a list of strings.
func ccSurfaces(c manifest.Command) []string {
	raw, _ := c.Surfaces["cc"].([]any)
	out := make([]string, 0, len(raw))
	for _, v := range raw {
		if s, ok := v.(string); ok {
			out = append(out, s)
		}
	}
	return out
}

// ccSignature renders how the command line takes the command's arguments,
// by the rule in manifest.Arg.Flag: the id positional and first, text through
// --file (stdin when absent, or --file - when the text is optional), every
// other argument a flag of its own name. A flag is shown optional ([...])
// when its type ends in ?, it has a default, or it is a bool. Pipes are
// escaped because the signature sits in a table cell.
func ccSignature(c manifest.Command) string {
	parts := []string{"bops " + c.Name}
	if _, ok := c.Args["id"]; ok {
		parts = append(parts, "<id>")
	}
	for _, an := range c.ArgNames() {
		a := c.Args[an]
		f := a.Flag(an)
		switch {
		case f == "":
			continue // the id, already placed
		case strings.HasPrefix(a.Type, "stdin|file"):
			if strings.HasSuffix(a.Type, "?") {
				parts = append(parts, "[--file <path>\\|-]")
			} else {
				parts = append(parts, "[--file <path>]")
			}
		case strings.HasSuffix(a.Type, "?") || a.Default != nil || a.Type == "bool":
			parts = append(parts, "[--"+f+"]")
		default:
			parts = append(parts, "--"+f+" <"+an+">")
		}
	}
	return strings.Join(parts, " ")
}
