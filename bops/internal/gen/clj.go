// Clj renders the Clojure binding (SPEC.md §8): bops.clj, namespace bops,
// with one fn per command whose surfaces.clj is "fn", each shelling out to
// `bops <command> --json`, and a Malli schema per output derived from the
// manifest; and bb.edn, so `bb -e "(require 'bops)"` loads it from the
// directory it is written to.
func Clj(m *manifest.Manifest) ([]File, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, ";; Generated by `bops gen clj` from bops/commands.json (contract %d). Do not edit.\n", m.Contract)
	b.WriteString(cljHead)
	fmt.Fprintf(&b, "\n(def contract\n  \"The bops contract this namespace was generated for. bops refuses nothing on\n   a mismatch, so check it against (:contract (:doc (version {}))).\"\n  %d)\n", m.Contract)

	env, err := cljSchemaFields(m.Common.Envelope)
	if err != nil {
		return nil, fmt.Errorf("gen clj: envelope: %w", err)
	}
	fmt.Fprintf(&b, "\n(def envelope\n  \"Malli schema of the fields every result carries, including a run that\n   could not complete (exit 1 or 2).\"\n  [:map%s])\n", env)

	b.WriteString("\n(def ^:private specs\n  \"Per command: whether it takes the bead id, how it takes text (:required\n   on stdin, :optional on stdin with --file -), and each option's kind.\"\n  {")
	var cmds []manifest.Command
	for _, c := range m.Commands {
		if s, _ := c.Surfaces["clj"].(string); s == "fn" {
			cmds = append(cmds, c)
		}
	}
	for i, c := range cmds {
		if i > 0 {
			b.WriteString("\n   ")
		}
		fmt.Fprintf(&b, "%q %s", c.Name, cljSpec(c))
	}
	b.WriteString("})\n")

	b.WriteString("\n(def output\n  \"Malli schema per command of a result from a run that completed (exit 0, or\n   3 for a negative verdict): the envelope plus the command's own output.\"\n  {")
	for i, c := range cmds {
		var out map[string]json.RawMessage
		if err := json.Unmarshal(c.Output, &out); err != nil {
			return nil, fmt.Errorf("gen clj: %s output: %w", c.Name, err)
		}
		all := map[string]json.RawMessage{}
		for k, v := range m.Common.Envelope {
			q, _ := json.Marshal(v)
			all[k] = q
		}
		for k, v := range out {
			all[k] = v
		}
		fields, err := cljSchemaRaw(all)
		if err != nil {
			return nil, fmt.Errorf("gen clj: %s output: %w", c.Name, err)
		}
		if i > 0 {
			b.WriteString("\n   ")
		}
		fmt.Fprintf(&b, "%q [:map%s]", c.Name, fields)
	}
	b.WriteString("})\n")
	b.WriteString(cljCall)

	for _, c := range cmds {
		b.WriteString(cljFn(c))
	}
	edn := "{:paths [\".\"]\n :deps {metosin/malli {:mvn/version \"0.16.1\"}}}\n"
	return []File{{Path: "bops.clj", Data: b.Bytes()}, {Path: "bb.edn", Data: []byte(edn)}}, nil
}

// cljArgKind classifies one argument for the generated argv builder.
func cljArgKind(name string, a manifest.Arg) string {
	switch {
	case a.Flag(name) == "":
		return "id"
	case strings.HasPrefix(a.Type, "stdin|file"):
		if strings.HasSuffix(a.Type, "?") {
			return "text?"
		}
		return "text"
	case a.Type == "bool":
		return "bool"
	case strings.HasSuffix(strings.TrimSuffix(a.Type, "?"), "[]"):
		return "list"
	}
	return "value"
}

func cljRequired(a manifest.Arg) bool {
	return a.Default == nil && !strings.HasSuffix(a.Type, "?") && a.Type != "bool"
}

func cljSpec(c manifest.Command) string {
	id := "false"
	text := "nil"
	var opts, req []string
	for _, an := range c.ArgNames() {
		a := c.Args[an]
		switch k := cljArgKind(an, a); k {
		case "id":
			id = "true"
			if strings.HasSuffix(a.Type, "?") {
				id = ":optional"
			}
		case "text":
			text = ":required"
		case "text?":
			text = ":optional"
		default:
			opts = append(opts, ":"+an+" :"+k)
			if k == "value" && cljRequired(a) {
				req = append(req, ":"+an)
			}
		}
	}
	return fmt.Sprintf("{:id? %s :text %s :opts {%s} :required #{%s}}", id, text, strings.Join(opts, ", "), strings.Join(req, " "))
}

func cljFn(c manifest.Command) string {
	var id, idOptional, text bool
	var optDoc []string
	for _, an := range c.ArgNames() {
		a := c.Args[an]
		switch k := cljArgKind(an, a); k {
		case "id":
			id, idOptional = true, strings.HasSuffix(a.Type, "?")
		case "text":
			text = true
		case "text?":
			optDoc = append(optDoc, ":text (string, sent on stdin)")
		default:
			d := ":" + an + " (" + strings.ReplaceAll(a.Type, "|", " or ")
			if a.Type == "enum" {
				d = ":" + an + " (one of " + strings.Join(a.Values, ", ")
			}
			if cljRequired(a) && k == "value" {
				d += ", required"
			}
			optDoc = append(optDoc, d+")")
		}
	}
	params := "cfg"
	callID := "nil"
	if id {
		params += " id"
		callID = "id"
	}
	if text {
		params += " text"
	}
	doc := c.Intent
	if doc == "" {
		doc = "bops " + c.Name
	}
	doc += ". Runs `bops " + c.Name + "`; returns {:exit :doc :err}."
	if idOptional {
		doc += " id may be nil."
	}
	if len(optDoc) > 0 {
		doc += "\n   opts: " + strings.Join(optDoc, "; ") + "."
	}
	if text {
		doc += "\n   text is sent on stdin."
	}
	optsArg := "opts"
	if text {
		optsArg = "(assoc opts :text text)"
	}
	return fmt.Sprintf("\n(defn %s\n  %q\n  ([%s] (%s %s {}))\n  ([%s opts] (call cfg %q %s %s)))\n",
		c.Name, doc, params, c.Name, params, params, c.Name, callID, optsArg)
}

func cljSchemaFields(fields map[string]string) (string, error) {
	raw := map[string]json.RawMessage{}
	for k, v := range fields {
		q, _ := json.Marshal(v)
		raw[k] = q
	}
	return cljSchemaRaw(raw)
}

// cljSchemaRaw renders the entries of a Malli :map from a manifest output
// object: keys sorted, a type ending in ? optional and [:maybe ...].
func cljSchemaRaw(fields map[string]json.RawMessage) (string, error) {
	keys := make([]string, 0, len(fields))
	for k := range fields {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	for _, k := range keys {
		s, optional, err := cljSchema(fields[k])
		if err != nil {
			return "", fmt.Errorf("%s: %w", k, err)
		}
		if optional {
			fmt.Fprintf(&b, " [:%s {:optional true} [:maybe %s]]", k, s)
		} else {
			fmt.Fprintf(&b, " [:%s %s]", k, s)
		}
	}
	return b.String(), nil
}

// cljSchema maps one manifest output value to a Malli schema: an object to
// [:map ...], a one-element array to [:vector ...], and a type string by
// cljType. It reports whether the field is optional.
func cljSchema(raw json.RawMessage) (string, bool, error) {
	switch t := bytes.TrimSpace(raw); {
	case len(t) > 0 && t[0] == '{':
		var obj map[string]json.RawMessage
		if err := json.Unmarshal(t, &obj); err != nil {
			return "", false, err
		}
		f, err := cljSchemaRaw(obj)
		return "[:map" + f + "]", false, err
	case len(t) > 0 && t[0] == '[':
		var arr []json.RawMessage
		if err := json.Unmarshal(t, &arr); err != nil || len(arr) != 1 {
			return "", false, fmt.Errorf("an array type must have one element")
		}
		s, _, err := cljSchema(arr[0])
		return "[:vector " + s + "]", false, err
	}
	var s string
	if err := json.Unmarshal(raw, &s); err != nil {
		return "", false, err
	}
	return cljType(s)
}

// cljType maps a type string: a note in parentheses is dropped; a trailing ?
// makes the field optional and nullable; T[] is a vector of T; a|b|c is an
// enum; string, int, bool and object are :string, :int, :boolean and :map.
func cljType(s string) (string, bool, error) {
	if i := strings.Index(s, " ("); i >= 0 {
		s = s[:i]
	}
	optional := strings.HasSuffix(s, "?")
	s = strings.TrimSuffix(s, "?")
	if strings.HasSuffix(s, "[]") {
		inner, _, err := cljType(strings.TrimSuffix(s, "[]"))
		return "[:vector " + inner + "]", optional, err
	}
	switch s {
	case "string":
		return ":string", optional, nil
	case "int":
		return ":int", optional, nil
	case "bool":
		return ":boolean", optional, nil
	case "object":
		return ":map", optional, nil
	}
	if strings.Contains(s, "|") {
		vals := strings.Split(s, "|")
		for i, v := range vals {
			vals[i] = fmt.Sprintf("%q", v)
		}
		return "[:enum " + strings.Join(vals, " ") + "]", optional, nil
	}
	return "", false, fmt.Errorf("unknown output type %q", s)
}

const cljHead = `(ns bops
  "One fn per bops command (bops/commands.json), each shelling out to
   ` + "`bops <command> --json`" + ` and returning {:exit n :doc parsed-json :err stderr}.
   Exit 0 is done, 1 could not run, 2 usage, 3 a negative verdict (lost,
   refused): a verdict, not a failure, so no fn throws on an exit status. They
   throw only on a bad call (a missing required option, an unknown one)
   before bops runs. Every fn takes cfg first: :bops-path (default \"bops\")
   and :actor (passed as BEADS_ACTOR). Needs babashka.process and cheshire
   (built into Babashka) and Malli."
  (:refer-clojure :exclude [next sync])
  (:require [babashka.process :as p]
            [cheshire.core :as json]
            [clojure.string :as str]
            [malli.core :as m]))
`

const cljCall = `
(defn run
  "Run bops with argv and --json. Never throws on an exit status: returns
   {:exit n :doc parsed-json-or-nil :err stderr}. cfg's :in, when set, is
   written to bops's stdin."
  [{:keys [bops-path actor in] :or {bops-path "bops"}} & argv]
  (let [opts (cond-> {:continue true}
               actor (assoc :extra-env {"BEADS_ACTOR" actor})
               in    (assoc :in in))
        {:keys [exit out err]} (apply p/sh opts bops-path (concat argv ["--json"]))]
    {:exit exit
     :err  err
     :doc  (try (json/parse-string out true) (catch Exception _ nil))}))

(defn argv
  "Pure: the command line for command, the bead id (nil when it takes none)
   and opts, by its spec. Options in name order, then --file - for optional
   text. Throws ex-info on a missing id, text or required option, and on an
   option the command does not take."
  [command id opts]
  (let [{:keys [id? text required] :as spec} (or (specs command)
                                                 (throw (ex-info (str "bops has no command " command) {:command command})))
        kinds (:opts spec)
        extra (remove (conj (set (keys kinds)) :text) (keys opts))]
    (when (seq extra)
      (throw (ex-info (str "bops " command " takes no option " (str/join ", " extra)) {:command command :options extra})))
    (when (and (true? id?) (str/blank? id))
      (throw (ex-info (str "bops " command " needs a bead id") {:command command})))
    (when (and id? (string? id) (str/starts-with? id "-"))
      (throw (ex-info (str "bops " command ": a bead id must not start with -") {:command command :id id})))
    (when (and (= :required text) (str/blank? (:text opts)))
      (throw (ex-info (str "bops " command " needs text") {:command command})))
    (doseq [k required]
      (when (nil? (get opts k))
        (throw (ex-info (str "bops " command " needs " k) {:command command :option k}))))
    (-> [command]
        (cond-> (and id? (not (str/blank? id))) (conj id))
        (into (mapcat (fn [[k kind]]
                        (let [v (get opts k) flag (str "--" (name k))]
                          (cond
                            ;; An explicit nil --only is an empty list (refused), never "no filter".
                            (and (nil? v) (#{"reap" "gc"} command) (= k :only) (contains? opts k)) [(str flag "=")]
                            (nil? v)       []
                            (= kind :bool) [(if v flag (str flag "=false"))]
                            (= kind :list) [flag (str/join "," v)]
                            :else          [flag (str v)])))
                      (sort-by key kinds)))
        (cond-> (and (= :optional text) (:text opts)) (conj "--file" "-")))))

(defn call
  "Run command with the bead id (nil when it takes none) and opts, sending
   (:text opts) on stdin. Returns run's map."
  [cfg command id opts]
  (let [args (argv command id opts)
        cfg  (cond-> cfg (:text opts) (assoc :in (:text opts)))]
    (apply run cfg args)))

(defn valid?
  "Whether doc, a parsed result of command from a run that completed (exit 0
   or 3), matches its output schema. Check a run that could not complete
   (exit 1 or 2) against envelope."
  [command doc]
  (m/validate (output command) doc))

(defn explain
  "Malli's explanation of why doc does not match command's output, or nil."
  [command doc]
  (m/explain (output command) doc))
`
