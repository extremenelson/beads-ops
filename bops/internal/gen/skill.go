// skillPreamble is the hand-written part of every agent skill: frontmatter
// and the loop prose, harness-neutral. The command reference after it is
// generated.
//
//go:embed templates/skill-preamble.md
var skillPreamble []byte

// ccBopsNext is the Claude Code /bops-next slash command, emitted when the
// manifest offers next to the skill.
//
//go:embed templates/cc-bops-next.md
var ccBopsNext []byte

// harness is what differs between the agent bindings that share the skill
// prose (SPEC.md §8): the surfaces key they read, and the shape of their
// hooks file.
type harness struct {
	target  string // bops gen <target>
	key     string // surfaces.<key>
	matcher string // SessionStart matcher
	status  string // statusMessage, for harnesses that show one
	comment string // _comment in hooks.json, after the generated line
	// guard is the _comment of guard-hooks.json, the opt-in fragment
	// carrying PreToolUse hooks; empty when the harness takes none.
	guard string
}

var (
	claudeCode = harness{
		target:  "cc",
		key:     "cc",
		comment: "Merge into .claude/settings.json; bindings/claude-code/README.md says why there is no Stop or PreCompact hook.",
		guard:   "Opt-in: merge into .claude/settings.json beside hooks.json to refuse bd update --claim, bd ready --claim and bd reclaim while the claim lock is on. It fails open: `|| true` allows the call when bops cannot run.",
	}
	codex = harness{
		target:  "codex",
		key:     "codex",
		matcher: "startup|resume|clear",
		status:  "Loading bops context",
		comment: "Merge into .codex/hooks.json in place of bd's SessionStart hook; see bindings/codex/README.md.",
	}
)

// Options are what a repo's .bops.json changes in the agent bindings.
type Options struct {
	// Branch is the branch the skill names for a bead's worktree
	// (branch_pattern); empty means config.DefaultBranchPattern.
	Branch string
}

// defaultBranch is config.DefaultBranchPattern, kept here so the generators
// stay pure functions of the manifest and their options.
const defaultBranch = "work/<id>"

// branchSlot is where the preamble names the branch.
var branchSlot = []byte("{branch}")

// CC renders the Claude Code binding (SPEC.md §8): skills/bops/SKILL.md (the
// preamble plus a reference of every command whose surfaces.cc lists
// "skill"), hooks.json (one SessionStart hook per command listing
// "hook:SessionStart"), guard-hooks.json (the opt-in PreToolUse hooks, one
// per command listing "hook:PreToolUse", written only when one does) and
// commands/bops-next.md.
func CC(m *manifest.Manifest) ([]File, error) { return CCWith(m, Options{}) }

// CCWith is CC for a repo whose .bops.json sets o.
func CCWith(m *manifest.Manifest, o Options) ([]File, error) {
	files, skill, err := agentBinding(m, claudeCode, o)
	if err != nil {
		return nil, err
	}
	for _, c := range skill {
		if c.Name == "next" {
			files = append(files, File{Path: "commands/bops-next.md", Data: ccBopsNext})
		}
	}
	return files, nil
}

// Codex renders the Codex binding (SPEC.md §8): skills/bops/SKILL.md, for
// .agents/skills/bops, and a hooks.json fragment to merge into
// .codex/hooks.json, both from surfaces.codex.
func Codex(m *manifest.Manifest) ([]File, error) { return CodexWith(m, Options{}) }

// CodexWith is Codex for a repo whose .bops.json sets o.
func CodexWith(m *manifest.Manifest, o Options) ([]File, error) {
	files, _, err := agentBinding(m, codex, o)
	return files, err
}

// agentBinding renders the skill and hooks fragment for h, and returns the
// commands the skill lists.
func agentBinding(m *manifest.Manifest, h harness, o Options) ([]File, []manifest.Command, error) {
	var skill []manifest.Command
	hooks := map[string][]hookGroup{}
	guards := map[string][]hookGroup{} // PreToolUse, in their own opt-in file
	for _, c := range m.Commands {
		for _, s := range surfaces(c, h.key) {
			switch {
			case s == "skill":
				skill = append(skill, c)
			case strings.HasPrefix(s, "hook:"):
				ev := strings.TrimPrefix(s, "hook:")
				g, err := hook(c, ev, h)
				if err != nil {
					return nil, nil, err
				}
				if ev == "PreToolUse" {
					guards[ev] = append(guards[ev], g)
				} else {
					hooks[ev] = append(hooks[ev], g)
				}
			default:
				return nil, nil, fmt.Errorf("gen %s: %s: unknown %s surface %q", h.target, c.Name, h.key, s)
			}
		}
	}
	if len(skill) == 0 {
		return nil, nil, fmt.Errorf("gen %s: no command has a %s skill surface", h.target, h.key)
	}

	branch := o.Branch
	if branch == "" {
		branch = defaultBranch
	}
	preamble := bytes.ReplaceAll(skillPreamble, branchSlot, []byte(branch))
	var b bytes.Buffer
	b.Write(preamble)
	if !bytes.HasSuffix(preamble, []byte("\n")) {
		b.WriteString("\n")
	}
	fmt.Fprintf(&b, "\n## Command reference (contract %d)\n\n", m.Contract)
	fmt.Fprintf(&b, "Generated by `bops gen %s`. If `bops version` reports a contract other than %d, stop and tell the person: this skill does not match the binary.\n\n", h.target, m.Contract)
	b.WriteString("Exit codes: ")
	codes := make([]string, 0, len(m.Common.Exit))
	for k := range m.Common.Exit {
		codes = append(codes, k)
	}
	sort.Strings(codes)
	for i, k := range codes {
		if i > 0 {
			b.WriteString("; ")
		}
		fmt.Fprintf(&b, "**%s** %s", k, m.Common.Exit[k])
	}
	b.WriteString(".\n\n| Command | Kind | Intent |\n|---|---|---|\n")
	for _, c := range skill {
		// A preview-only command shows no --dry-run and the kind preview: the
		// skill runs its dry run, and a person the real one (SPEC §4).
		kind := c.Kind
		if c.PreviewOnly() {
			kind = "preview"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", signature(c), kind, c.Intent)
	}
	files := []File{{Path: "skills/bops/SKILL.md", Data: b.Bytes()}}

	hj, err := hooksFile(m, h, h.comment, hooks)
	if err != nil {
		return nil, nil, fmt.Errorf("gen %s: hooks.json: %w", h.target, err)
	}
	files = append(files, File{Path: "hooks.json", Data: hj})
	if len(guards) > 0 {
		gj, err := hooksFile(m, h, h.guard, guards)
		if err != nil {
			return nil, nil, fmt.Errorf("gen %s: guard-hooks.json: %w", h.target, err)
		}
		files = append(files, File{Path: "guard-hooks.json", Data: gj})
	}
	return files, skill, nil
}

func hooksFile(m *manifest.Manifest, h harness, comment string, hooks map[string][]hookGroup) ([]byte, error) {
	b, err := json.MarshalIndent(struct {
		Comment string                 `json:"_comment"`
		Hooks   map[string][]hookGroup `json:"hooks"`
	}{
		Comment: fmt.Sprintf("Generated by `bops gen %s` from bops/commands.json (contract %d). %s", h.target, m.Contract, comment),
		Hooks:   hooks,
	}, "", "  ")
	return append(b, '\n'), err
}

type hookGroup struct {
	Matcher string    `json:"matcher"`
	Hooks   []hookCmd `json:"hooks"`
}

type hookCmd struct {
	Type          string `json:"type"`
	Command       string `json:"command"`
	StatusMessage string `json:"statusMessage,omitempty"`
}

// hook builds the hook entry for a command. Only SessionStart, and on
// Claude Code an opt-in PreToolUse hook on Bash, are generated: Stop fires
// after every reply, too often for a pushing sync, and a PreCompact hook's
// output never reaches the model (SPEC.md §8). The command must take
// --hook-json, since both harnesses parse bare JSON on stdout as hook control
// and inject only hookSpecificOutput.additionalContext. A PreToolUse command
// answers with hookSpecificOutput.permissionDecision, so `|| true` (a missing
// or failing bops) allows the call.
func hook(c manifest.Command, event string, h harness) (hookGroup, error) {
	matcher := h.matcher
	switch {
	case event == "SessionStart":
	case event == "PreToolUse" && h.guard != "":
		matcher = "Bash"
	default:
		return hookGroup{}, fmt.Errorf("gen %s: %s: hook:%s: only SessionStart hooks, and PreToolUse on cc, are generated (SPEC.md §8)", h.target, c.Name, event)
	}
	if _, ok := c.Args["hook-json"]; !ok {
		return hookGroup{}, fmt.Errorf("gen %s: %s: hook:%s needs a hook-json arg to wrap its output for the harness", h.target, c.Name, event)
	}
	return hookGroup{Matcher: matcher, Hooks: []hookCmd{{Type: "command", Command: "bops " + c.Name + " --hook-json || true", StatusMessage: h.status}}}, nil
}

// surfaces reads surfaces.<key>, a list of strings.
func surfaces(c manifest.Command, key string) []string {
	raw, _ := c.Surfaces[key].([]any)
	out := make([]string, 0, len(raw))
	for _, v := range raw {
		if s, ok := v.(string); ok {
			out = append(out, s)
		}
	}
	return out
}

// signature renders how the command line takes the command's arguments,
// by the rule in manifest.Arg.Flag: the id positional and first, text through
// --file (stdin when absent, or --file - when the text is optional), every
// other argument a flag of its own name, except a preview-only command's
// dry-run, which agents never pass. A flag is shown optional ([...])
// when its type ends in ?, it has a default, or it is a bool. Pipes are
// escaped because the signature sits in a table cell.
func signature(c manifest.Command) string {
	parts := []string{"bops " + c.Name}
	if a, ok := c.Args["id"]; ok {
		if strings.HasSuffix(a.Type, "?") {
			parts = append(parts, "[<id>]")
		} else {
			parts = append(parts, "<id>")
		}
	}
	for _, an := range c.ArgNames() {
		a := c.Args[an]
		f := a.Flag(an)
		switch {
		case f == "":
			continue // the id, already placed
		case an == "dry-run" && c.PreviewOnly():
			continue // agents run only the dry run, the default
		case strings.HasPrefix(a.Type, "stdin|file"):
			if strings.HasSuffix(a.Type, "?") {
				parts = append(parts, "[--file <path>\\|-]")
			} else {
				parts = append(parts, "[--file <path>]")
			}
		case strings.HasSuffix(a.Type, "?") || a.Default != nil || a.Type == "bool":
			parts = append(parts, "[--"+f+"]")
		default:
			parts = append(parts, "--"+f+" <"+an+">")
		}
	}
	return strings.Join(parts, " ")
}
