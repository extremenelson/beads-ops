// Codex gets the same prose as Claude Code (SPEC §8); only the reference,
// built from surfaces.codex, and the generator's name differ.
func TestCodexSkillSharesThePreamble(t *testing.T) {
	m := embedded(t)
	cc := ccFiles(t, m)["skills/bops/SKILL.md"]
	cx := codexFiles(t)["skills/bops/SKILL.md"]
	head := func(s string) string { return s[:strings.Index(s, "## Command reference")] }
	if head(cc) != head(cx) {
		t.Fatal("the Codex skill's prose differs from the Claude Code skill's")
	}
	ref := cx[strings.Index(cx, "## Command reference (contract 1)"):]
	if !strings.Contains(ref, "Generated by `bops gen codex`.") {
		t.Error("reference does not name bops gen codex")
	}
	for _, c := range m.Commands {
		want := false
		if l, ok := c.Surfaces["codex"].([]any); ok {
			for _, s := range l {
				want = want || s == "skill"
			}
		}
		row := "| `bops " + c.Name
		if got := strings.Contains(ref, row+" ") || strings.Contains(ref, row+"`"); got != want {
			t.Errorf("bops %s: in reference = %v, want %v", c.Name, got, want)
		}
	}
	if n := len(cx) / 4; n >= 2000 {
		t.Errorf("SKILL.md is about %d tokens; the cap is 2000", n)
	}
}

// The Codex fragment uses upstream bd's Codex hook shape: SessionStart on
// startup|resume|clear, with a statusMessage. No slash command is emitted.
func TestCodexHooksAndFiles(t *testing.T) {
	files := codexFiles(t)
	if len(files) != 2 {
		t.Fatalf("files = %d, want SKILL.md and hooks.json", len(files))
	}
	var h struct {
		Hooks map[string][]struct {
			Matcher string `json:"matcher"`
			Hooks   []struct {
				Type, Command string
				StatusMessage string `json:"statusMessage"`
			}
		} `json:"hooks"`
	}
	if err := json.Unmarshal([]byte(files["hooks.json"]), &h); err != nil {
		t.Fatal(err)
	}
	if len(h.Hooks) != 1 || len(h.Hooks["SessionStart"]) != 1 {
		t.Fatalf("hooks = %+v, want one SessionStart group", h.Hooks)
	}
	g := h.Hooks["SessionStart"][0]
	if g.Matcher != "startup|resume|clear" || len(g.Hooks) != 1 ||
		g.Hooks[0].Command != "bops session-start --hook-json || true" || g.Hooks[0].StatusMessage == "" {
		t.Fatalf("SessionStart group = %+v", g)
	}
	if strings.Contains(ccFiles(t, embedded(t))["hooks.json"], "statusMessage") {
		t.Error("the Claude Code fragment gained a statusMessage")
	}
}

